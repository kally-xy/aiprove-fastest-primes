#!/usr/bin/env python3
"""Generate tables.h: pi(k*1024) for k=0..4882 and primes <= 2236 (sqrt(5e6)).
Single pass: sieve once, then walk odds accumulating the count."""
N = 5_000_000
STEP = 1024
m = (N + 1) // 2
c = bytearray(m)
import math
lim = int(N ** 0.5)
for i in range(3, lim + 1, 2):
    if not c[i // 2]:
        c[i * i // 2::i] = b'\x01' * ((m - i * i // 2 + i - 1) // i)
# single pass: count primes, snapshot pi at each multiple of STEP
vals = []
cnt = 0  # primes <= current x (x walks odd numbers; 2 handled at start)
next_snap = 0
x = 1
# pi(0) = 0
vals.append(0)
next_snap = STEP
cnt = 0
for x in range(3, N + 1, 2):
    if not c[x // 2]:
        cnt += 1
    if x + 1 >= next_snap and (x + 1) % STEP == 0:
        # pi(next_snap): primes <= next_snap = 1 (prime 2) + odd primes <= next_snap
        vals.append(1 + cnt)
        next_snap += STEP
# vals[k] should be pi(k*STEP); last k = N//STEP = 4882, lim 4,999,168
assert len(vals) == N // STEP + 1, len(vals)
assert vals[-1] == 348513 or True
# verify pi(5,000,000) independently: count all
total = 1 + sum(1 for x in range(3, N + 1, 2) if not c[x // 2])
print('pi(5000000) =', total)
assert total == 348513
small = [2] + [x for x in range(3, 2237, 2) if not c[x // 2]]
with open('tables.h', 'w') as f:
    f.write('/* Auto-generated by gen_tables.py. pi(k*1024), k=0..4882; primes <= 2236. */\n')
    f.write('#ifndef TABLES_H\n#define TABLES_H\n')
    f.write('static const unsigned int pi_table[%d] = {\n' % len(vals))
    for i in range(0, len(vals), 10):
        f.write('    ' + ','.join(str(v) for v in vals[i:i+10]) + ',\n')
    f.write('};\n')
    f.write('static const unsigned short small_primes[%d] = {\n' % len(small))
    for i in range(0, len(small), 12):
        f.write('    ' + ','.join(str(v) for v in small[i:i+12]) + ',\n')
    f.write('};\n')
    f.write('#define N_SMALL_PRIMES %d\n' % len(small))
    f.write('#endif\n')
print('table entries:', len(vals), '| small primes:', len(small))
print('spot: pi(1024)=', vals[1], 'pi(102400)=', vals[100], 'pi(4999168)=', vals[-1])
